const { chromium } = require("playwright");
const { execSync } = require("child_process");
const ok = (e, r, x) => console.log(`${e}: ${r} (esperado ${x})`);
const q = (sql) => execSync(`docker exec babylon-postgres psql -U babylon -d babylon -tAc "${sql.replace(/"/g, '\\"')}"`).toString().trim();
(async () => {
  const n = await chromium.launch({ executablePath: "/usr/bin/google-chrome" });
  const p = await n.newPage({ viewport: { width: 1280, height: 900 } });
  await p.goto("http://localhost:5173/login");
  await p.fill('input[name="email"]', "prueba-tmp-av-profe@prueba.babylon.test");
  await p.fill('input[name="password"]', "prueba1234");
  await p.click('button[type="submit"]');
  await p.waitForURL((u) => !u.pathname.startsWith("/login"));
  await p.goto("http://localhost:5173/calificaciones?curso=prueba-tmp-av-curso&vista=cierre&periodo=noviembre");
  await p.waitForSelector('input[type="number"], input[inputmode]');
  const campos = p.locator('input[type="number"]');
  const total = await campos.count();
  for (let i = 0; i < total; i++) await campos.nth(i).fill("7");
  await p.click("button:has-text('Guardar')");
  await p.waitForTimeout(1500);
  ok("notas de cierre guardadas", q("select count(*) from \"NotaCierre\" where \"cursoId\"='prueba-tmp-av-curso' and periodo='noviembre'"), String(total));
  await p.click("button:has-text('Publicar')");
  await p.waitForTimeout(500);
  const confirmar = p.locator("button:has-text('Publicar')").last();
  if (await confirmar.isVisible()) await confirmar.click();
  await p.waitForTimeout(1500);
  ok("notas de cierre publicadas", q("select count(*) from \"NotaCierre\" where \"cursoId\"='prueba-tmp-av-curso' and periodo='noviembre' and estado='publicada'"), String(total));
  ok("hay alumnos en el curso", total > 1 ? "sí" : "no", "sí");
  await n.close();
})();
